import os
import time
import random

import numpy as np
import torch
import torch.nn as nn
from torch.utils.data import DataLoader
from torchvision import datasets, transforms


# =========================================================
# 1) 난수 고정
# =========================================================
seed = 42
random.seed(seed)
np.random.seed(seed)
torch.manual_seed(seed)


# =========================================================
# 2) 데이터 전처리 (증강 + 정규화)
# =========================================================
CIFAR10_MEAN = (0.4914, 0.4822, 0.4465)
CIFAR10_STD = (0.2470, 0.2435, 0.2616)

CIFAR10_CLASSES = [
    "airplane", "automobile", "bird", "cat", "deer",
    "dog", "frog", "horse", "ship", "truck",
]

train_transform = transforms.Compose([
    transforms.RandomCrop(size=32, padding=4),
    transforms.RandomHorizontalFlip(p=0.5),
    transforms.ToTensor(),
    transforms.Normalize(mean=CIFAR10_MEAN, std=CIFAR10_STD),
])

test_transform = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize(mean=CIFAR10_MEAN, std=CIFAR10_STD),
])


# =========================================================
# 3) 모델 정의 (ConvBlock, CIFAR10CNN)
# =========================================================
class ConvBlock(nn.Module):
    """Conv → BN → ReLU → Conv → BN → ReLU → MaxPool"""

    def __init__(self, in_channels, out_channels):
        super().__init__()
        layers = [
            nn.Conv2d(in_channels, out_channels, kernel_size=3, stride=1, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(),
            nn.Conv2d(out_channels, out_channels, kernel_size=3, stride=1, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(),
            nn.MaxPool2d(kernel_size=2, stride=2),
        ]
        self.block = nn.Sequential(*layers)

    def forward(self, x):
        return self.block(x)


class CIFAR10CNN(nn.Module):
    """ConvBlock×3 → Global Average Pooling → Dropout → Linear"""

    def __init__(self):
        super().__init__()
        self.features = nn.Sequential(
            ConvBlock(in_channels=3, out_channels=64),     # [B, 64, 16, 16]
            ConvBlock(in_channels=64, out_channels=128),   # [B, 128, 8, 8]
            ConvBlock(in_channels=128, out_channels=256),  # [B, 256, 4, 4]
        )
        self.global_average_pool = nn.AdaptiveAvgPool2d(output_size=(1, 1))  # [B, 256, 1, 1]
        self.classifier = nn.Sequential(
            nn.Dropout(p=0.3),
            nn.Linear(in_features=256, out_features=10),
        )

    def forward(self, x):
        x = self.features(x)
        x = self.global_average_pool(x)
        x = torch.flatten(x, start_dim=1)  # [B, 256]
        logits = self.classifier(x)        # [B, 10]
        return logits


# =========================================================
# 4) 학습 / 평가 함수 (MNIST 실습과 동일)
# =========================================================
def train_one_epoch(model, data_loader, criterion, optimizer, device):
    model.train()
    total_loss, correct_count, sample_count = 0.0, 0, 0

    for images, labels in data_loader:
        images = images.to(device)
        labels = labels.to(device)

        optimizer.zero_grad()
        logits = model(images)
        loss = criterion(logits, labels)
        loss.backward()
        optimizer.step()

        batch_size = images.size(0)
        total_loss += loss.item() * batch_size
        correct_count += (logits.argmax(dim=1) == labels).sum().item()
        sample_count += batch_size

    return total_loss / sample_count, correct_count / sample_count


def evaluate(model, data_loader, criterion, device):
    model.eval()
    total_loss, correct_count, sample_count = 0.0, 0, 0

    with torch.no_grad():
        for images, labels in data_loader:
            images = images.to(device)
            labels = labels.to(device)

            logits = model(images)
            loss = criterion(logits, labels)

            batch_size = images.size(0)
            total_loss += loss.item() * batch_size
            correct_count += (logits.argmax(dim=1) == labels).sum().item()
            sample_count += batch_size

    return total_loss / sample_count, correct_count / sample_count


def sync(device):
    # GPU 시간 측정을 정확히 하기 위한 동기화 (CPU면 아무것도 안 함)
    if device.type == "cuda":
        torch.cuda.synchronize()


# =========================================================
# 5) 메인: 데이터 로드 → 학습 → 저장 → 불러오기
# =========================================================
def main():
    EPOCHS = 5
    SAVE_PATH = "src/models/CIFAR10/CIFAR10_CNN.pth"
    os.makedirs(os.path.dirname(SAVE_PATH), exist_ok=True)

    # ---- 데이터셋 / DataLoader ----
    train_dataset = datasets.CIFAR10(root="src/datasets", train=True, transform=train_transform, download=True)
    test_dataset = datasets.CIFAR10(root="src/datasets", train=False, transform=test_transform, download=True)
    print("Train data:", len(train_dataset))
    print("Test data:", len(test_dataset))

    train_loader = DataLoader(train_dataset, batch_size=32, shuffle=True, num_workers=0, pin_memory=True)
    test_loader = DataLoader(test_dataset, batch_size=128, shuffle=False, num_workers=0, pin_memory=True)

    # ---- 모델 / 디바이스 ----
    # 노트북은 GPU 전용이지만, GPU가 없으면 CPU로라도 돌아가게 함 (CPU는 매우 느림)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print("Device:", device)

    model = CIFAR10CNN().to(device)
    print("Total parameters:", sum(p.numel() for p in model.parameters()))

    # ---- 손실 함수 / Optimizer ----
    criterion = nn.CrossEntropyLoss()
    optimizer = torch.optim.AdamW(model.parameters(), lr=0.001)

    # ---- GPU Warm-up ----
    if device.type == "cuda":
        warmup_input = torch.zeros(64, 3, 32, 32, device=device)
        model.eval()
        with torch.no_grad():
            for _ in range(3):
                _ = model(warmup_input)
        sync(device)

    # ---- 학습 (노트북 TODO 부분) ----
    train_loss_history, train_accuracy_history = [], []
    test_loss_history, test_accuracy_history = [], []

    sync(device)
    training_start_time = time.perf_counter()

    for epoch in range(EPOCHS):
        sync(device)
        epoch_start_time = time.perf_counter()

        train_loss, train_accuracy = train_one_epoch(model, train_loader, criterion, optimizer, device)
        test_loss, test_accuracy = evaluate(model, test_loader, criterion, device)

        sync(device)
        epoch_time = time.perf_counter() - epoch_start_time

        train_loss_history.append(train_loss)
        train_accuracy_history.append(train_accuracy)
        test_loss_history.append(test_loss)
        test_accuracy_history.append(test_accuracy)

        print(
            f"Epoch {epoch + 1}/{EPOCHS} | "
            f"Train loss: {train_loss:.4f} | "
            f"Train accuracy: {train_accuracy * 100:.2f}% | "
            f"Test loss: {test_loss:.4f} | "
            f"Test accuracy: {test_accuracy * 100:.2f}% | "
            f"Time: {epoch_time:.2f}s"
        )

    sync(device)
    total_training_time = time.perf_counter() - training_start_time
    print(f"Total training time: {total_training_time:.2f}s")

    # ---- 모델 저장 ----
    save_data = {
        "model_name": "CIFAR10CNN",
        "model_state_dict": model.state_dict(),
        "optimizer_state_dict": optimizer.state_dict(),
        "test_accuracy": test_accuracy_history[-1],
        "epochs": EPOCHS,
        "class_names": CIFAR10_CLASSES,
        "mean": CIFAR10_MEAN,
        "std": CIFAR10_STD,
    }
    torch.save(save_data, SAVE_PATH)
    print("Saved:", SAVE_PATH)

    # ---- 모델 불러오기 (질문하신 부분) ----
    loaded_model = CIFAR10CNN()

    state_dict = torch.load(
        SAVE_PATH,  # 학습한 파일까지 제출
        map_location="cpu",
        weights_only=True,
    )

    loaded_model.load_state_dict(state_dict["model_state_dict"])
    loaded_model.to(device)
    loaded_model.eval()

    # ---- 제대로 불러와졌는지 확인 ----
    print("모델 이름:", state_dict["model_name"])
    print("Epoch 체크포인트:", state_dict["epochs"])
    print(f"마지막 테스트 정확도: {state_dict['test_accuracy'] * 100:.2f}%")

    _, loaded_accuracy = evaluate(loaded_model, test_loader, criterion, device)
    print(f"불러온 모델 테스트 정확도: {loaded_accuracy * 100:.2f}%")


if __name__ == "__main__":
    main()